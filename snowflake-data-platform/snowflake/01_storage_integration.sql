USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE STORAGE INTEGRATION S3_SNOWFLAKE_DEMO_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<AWS_ACCOUNT_ID>:role/<SNOWFLAKE_ROLE_NAME>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET_NAME>/snowflake-demo/');

DESC INTEGRATION S3_SNOWFLAKE_DEMO_INT;

GRANT USAGE ON INTEGRATION S3_SNOWFLAKE_DEMO_INT TO ROLE DE_LOADER;

