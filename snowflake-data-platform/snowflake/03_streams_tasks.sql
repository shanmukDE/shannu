USE ROLE ACCOUNTADMIN;
USE DATABASE SNOWFLAKE_DEMO;
USE WAREHOUSE DE_WH;

CREATE OR REPLACE STREAM RAW.ORDERS_RAW_STREAM ON TABLE RAW.ORDERS_RAW APPEND_ONLY = TRUE;

CREATE OR REPLACE TABLE STAGING.ORDERS_INCREMENTAL (
  ORDER_ID STRING,
  CUSTOMER_ID STRING,
  ORDER_TS TIMESTAMP_TZ,
  STATUS STRING,
  CURRENCY STRING,
  ITEMS VARIANT,
  SOURCE_FILE STRING,
  INGESTED_AT TIMESTAMP_TZ,
  PROCESSED_AT TIMESTAMP_TZ
);

CREATE OR REPLACE TASK STAGING.PROCESS_ORDERS_TASK
  WAREHOUSE = DE_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('SNOWFLAKE_DEMO.RAW.ORDERS_RAW_STREAM')
AS
INSERT INTO STAGING.ORDERS_INCREMENTAL
SELECT
  PAYLOAD:order_id::STRING,
  PAYLOAD:customer_id::STRING,
  PAYLOAD:order_ts::TIMESTAMP_TZ,
  UPPER(PAYLOAD:status::STRING),
  UPPER(COALESCE(PAYLOAD:currency::STRING, 'USD')),
  PAYLOAD:items,
  SOURCE_FILE,
  INGESTED_AT,
  CURRENT_TIMESTAMP()
FROM RAW.ORDERS_RAW_STREAM
WHERE METADATA$ACTION = 'INSERT';

ALTER TASK STAGING.PROCESS_ORDERS_TASK RESUME;

