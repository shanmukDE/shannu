USE ROLE ACCOUNTADMIN;
USE DATABASE SNOWFLAKE_DEMO;

CREATE OR REPLACE SECURE VIEW ANALYTICS.VW_PARTNER_DAILY_SALES AS
SELECT ORDER_DATE, PRODUCT_ID, QUANTITY, NET_SALES
FROM ANALYTICS.RPT_DAILY_SALES;

CREATE SHARE IF NOT EXISTS SALES_ANALYTICS_SHARE;
GRANT USAGE ON DATABASE SNOWFLAKE_DEMO TO SHARE SALES_ANALYTICS_SHARE;
GRANT USAGE ON SCHEMA SNOWFLAKE_DEMO.ANALYTICS TO SHARE SALES_ANALYTICS_SHARE;
GRANT SELECT ON VIEW SNOWFLAKE_DEMO.ANALYTICS.VW_PARTNER_DAILY_SALES TO SHARE SALES_ANALYTICS_SHARE;

