USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE ROLE DE_LOADER;
CREATE OR REPLACE ROLE DE_TRANSFORMER;
CREATE OR REPLACE ROLE BI_READER;

CREATE WAREHOUSE IF NOT EXISTS DE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS SNOWFLAKE_DEMO;
CREATE SCHEMA IF NOT EXISTS SNOWFLAKE_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS SNOWFLAKE_DEMO.STAGING;
CREATE SCHEMA IF NOT EXISTS SNOWFLAKE_DEMO.ANALYTICS;

GRANT USAGE ON WAREHOUSE DE_WH TO ROLE DE_LOADER;
GRANT USAGE ON WAREHOUSE DE_WH TO ROLE DE_TRANSFORMER;
GRANT USAGE ON WAREHOUSE DE_WH TO ROLE BI_READER;
GRANT USAGE ON DATABASE SNOWFLAKE_DEMO TO ROLE DE_LOADER;
GRANT USAGE ON DATABASE SNOWFLAKE_DEMO TO ROLE DE_TRANSFORMER;
GRANT USAGE ON DATABASE SNOWFLAKE_DEMO TO ROLE BI_READER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE PIPE ON SCHEMA SNOWFLAKE_DEMO.RAW TO ROLE DE_LOADER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE TASK ON SCHEMA SNOWFLAKE_DEMO.STAGING TO ROLE DE_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE MATERIALIZED VIEW ON SCHEMA SNOWFLAKE_DEMO.ANALYTICS TO ROLE DE_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SNOWFLAKE_DEMO.ANALYTICS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SNOWFLAKE_DEMO.ANALYTICS TO ROLE BI_READER;

