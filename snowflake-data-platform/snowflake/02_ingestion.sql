USE ROLE DE_LOADER;
USE DATABASE SNOWFLAKE_DEMO;
USE SCHEMA RAW;
USE WAREHOUSE DE_WH;

CREATE OR REPLACE FILE FORMAT JSON_FF TYPE = JSON STRIP_OUTER_ARRAY = TRUE;
CREATE OR REPLACE FILE FORMAT CSV_FF TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = ('', 'NULL');

CREATE OR REPLACE STAGE ORDERS_STAGE
  URL = 's3://<BUCKET_NAME>/snowflake-demo/orders/'
  STORAGE_INTEGRATION = S3_SNOWFLAKE_DEMO_INT
  FILE_FORMAT = JSON_FF;

CREATE OR REPLACE TABLE ORDERS_RAW (
  PAYLOAD VARIANT,
  SOURCE_FILE STRING,
  SOURCE_ROW_NUMBER NUMBER,
  INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE PIPE ORDERS_PIPE AUTO_INGEST = TRUE AS
COPY INTO ORDERS_RAW (PAYLOAD, SOURCE_FILE, SOURCE_ROW_NUMBER, INGESTED_AT)
FROM (SELECT $1, METADATA$FILENAME, METADATA$FILE_ROW_NUMBER, CURRENT_TIMESTAMP() FROM @ORDERS_STAGE)
ON_ERROR = 'CONTINUE';

