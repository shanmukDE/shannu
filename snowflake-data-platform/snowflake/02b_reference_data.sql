USE ROLE DE_LOADER;
USE DATABASE SNOWFLAKE_DEMO;
USE SCHEMA RAW;
USE WAREHOUSE DE_WH;

CREATE OR REPLACE STAGE CUSTOMERS_STAGE
  URL = 's3://<BUCKET_NAME>/snowflake-demo/customers/'
  STORAGE_INTEGRATION = S3_SNOWFLAKE_DEMO_INT
  FILE_FORMAT = CSV_FF;

CREATE OR REPLACE STAGE PRODUCTS_STAGE
  URL = 's3://<BUCKET_NAME>/snowflake-demo/products/'
  STORAGE_INTEGRATION = S3_SNOWFLAKE_DEMO_INT
  FILE_FORMAT = CSV_FF;

CREATE OR REPLACE TABLE CUSTOMERS (
  CUSTOMER_ID STRING,
  CUSTOMER_NAME STRING,
  EMAIL STRING,
  STATE STRING,
  UPDATED_AT TIMESTAMP_TZ
);

CREATE OR REPLACE TABLE PRODUCTS (
  PRODUCT_ID STRING,
  PRODUCT_NAME STRING,
  CATEGORY STRING,
  UNIT_COST NUMBER(18,2),
  UPDATED_AT TIMESTAMP_TZ
);

COPY INTO CUSTOMERS FROM @CUSTOMERS_STAGE FILE_FORMAT = CSV_FF ON_ERROR = 'ABORT_STATEMENT';
COPY INTO PRODUCTS FROM @PRODUCTS_STAGE FILE_FORMAT = CSV_FF ON_ERROR = 'ABORT_STATEMENT';

